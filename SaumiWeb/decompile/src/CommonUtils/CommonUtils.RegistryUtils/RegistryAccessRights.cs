using System;

namespace CommonUtils.RegistryUtils;

[Flags]
public enum RegistryAccessRights
{
	DELETE = 0x10000,
	READ_CONTROL = 0x20000,
	WRITE_DAC = 0x40000,
	WRITE_OWNER = 0x80000,
	SYNCHRONIZE = 0x100000,
	STANDARD_RIGHTS_EXECUTE = READ_CONTROL,
	STANDARD_RIGHTS_READ = READ_CONTROL,
	STANDARD_RIGHTS_WRITE = READ_CONTROL,
	STANDARD_RIGHTS_REQUIRED = DELETE | READ_CONTROL | WRITE_DAC | WRITE_OWNER,
	STANDARD_RIGHTS_ALL = STANDARD_RIGHTS_REQUIRED | SYNCHRONIZE,
	KEY_QUERY_VALUE = 1,
	KEY_SET_VALUE = 2,
	KEY_CREATE_SUB_KEY = 4,
	KEY_ENUMERATE_SUB_KEYS = 8,
	KEY_NOTIFY = 0x10,
	KEY_CREATE_LINK = 0x20,
	KEY_READ = READ_CONTROL | KEY_QUERY_VALUE | KEY_ENUMERATE_SUB_KEYS | KEY_NOTIFY,
	KEY_EXECUTE = KEY_READ,
	KEY_WRITE = READ_CONTROL | KEY_SET_VALUE | KEY_CREATE_SUB_KEY,
	KEY_ALL_ACCESS = STANDARD_RIGHTS_REQUIRED | KEY_QUERY_VALUE | KEY_SET_VALUE | KEY_CREATE_SUB_KEY | KEY_ENUMERATE_SUB_KEYS | KEY_NOTIFY | KEY_CREATE_LINK,
	KEY_WOW64_64KEY = 0x100,
	KEY_WOW64_32KEY = 0x200
}
