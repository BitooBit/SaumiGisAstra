	public static bool RemoveConfigurations(string path, string datasource)
	{
		UtilsLoggerWrapper.Info($"Searching and removing configuration {datasource} from file {path}");
		if (!File.Exists(path))
		{
			UtilsLoggerWrapper.Error($"Can't remove specified configuration, file \"{path}\" doesn't exist!");
			return false;
		}
		UtilsLoggerWrapper.Info($"Reading all text from file {path}");
		FileStream fileStream = File.Open(path, FileMode.Open);
		StreamReader streamReader = new StreamReader(fileStream, Encoding.Default);
		string text = streamReader.ReadToEnd();
		streamReader.Close();
		streamReader.Dispose();
		fileStream.Close();
		fileStream.Dispose();
		UtilsLoggerWrapper.Info($"Modifying read text with removing configuration {datasource}");
		for (int num = text.IndexOf(datasource); num >= 0; num = ((num < text.Length) ? text.IndexOf(datasource, num + 1) : (-1)))
		{
			string text2 = text.Substring(num, text.IndexOf('(', num) - num - 1).Replace(" ", string.Empty).Replace("\t", string.Empty)
				.Replace("\r", string.Empty)
				.Replace("\n", string.Empty);
			if (text2.Equals($"{datasource}="))
			{
				int num2 = 0;
				int num3 = 0;
				string text3 = text.Substring(num);
				bool flag = false;
				string text4 = text3;
				foreach (char c in text4)
				{
					if (flag)
					{
						break;
					}
					num2++;
					switch (c)
					{
					case '(':
						num3++;
						break;
					case ')':
						num3--;
						if (num3 <= 0)
						{
							flag = true;
						}
						break;
					}
				}
				text = text.Remove(num, num2);
				text = text.Replace(string.Format("{0}{0}{0}", Environment.NewLine), Environment.NewLine);
			}
		}
		UtilsLoggerWrapper.Info($"Rewriting file {path} with modifed configurations text");
		FileStream fileStream2 = File.Open(path, FileMode.Truncate);
		StreamWriter streamWriter = new StreamWriter(fileStream2, Encoding.Default);
		streamWriter.Write(text);
		streamWriter.Close();
		streamWriter.Dispose();
		fileStream2.Close();
		fileStream2.Dispose();
		return true;
	}

	public static bool RenameConfiguration(string path, string oldName, string newName)
	{
		UtilsLoggerWrapper.Info($"Renaming configuration {oldName} to {newName} in file {path}");
		if (!File.Exists(path))
		{
			UtilsLoggerWrapper.Error($"Can't rename specified configuration, file \"{path}\" doesn't exist!");
			return false;
		}
		UtilsLoggerWrapper.Info($"Reading all text from file {path}");
		FileStream fileStream = File.Open(path, FileMode.Open);
		StreamReader streamReader = new StreamReader(fileStream, Encoding.Default);
		string text = streamReader.ReadToEnd();
		streamReader.Close();
		streamReader.Dispose();
		fileStream.Close();
		fileStream.Dispose();
		UtilsLoggerWrapper.Info($"Modifying read text with replacing configuration name {oldName} to {newName}");
		int num = text.IndexOf(oldName);
		if (num < 0)
		{
			UtilsLoggerWrapper.Error(string.Format("ERROR! Configuration {0} doesn't exists! Can't rename database configuration from {0} to {1}...", oldName, newName));
			return false;
		}
		int num2 = text.IndexOf('=', num) + 1;
		string text2 = text.Substring(num, num2 - num);
		string text3 = text2.Replace(" ", string.Empty).Replace("\t", string.Empty).Replace("\r", string.Empty)
			.Replace("\n", string.Empty);
		if (text3.Equals($"{oldName}="))
		{
			text = text.Replace(text2, $"{newName} =");
		}
		UtilsLoggerWrapper.Info($"Rewriting file {path} with modifed configurations text");
		FileStream fileStream2 = File.Open(path, FileMode.Truncate);
		StreamWriter streamWriter = new StreamWriter(fileStream2, Encoding.Default);
		streamWriter.Write(text);
		streamWriter.Close();
		streamWriter.Dispose();
		fileStream2.Close();
		fileStream2.Dispose();
		return true;
	}

	public static void CopyConfiguration(TnsNamesConfiguration sourceConfiguration, TnsNamesOraFile targetFile)
	{
		string path = targetFile.Path;
		string datasourceName = sourceConfiguration.DatasourceName;
		string databaseHost = sourceConfiguration.DatabaseHost;
		string databasePort = sourceConfiguration.DatabasePort;
		string databaseServiceName = sourceConfiguration.DatabaseServiceName;
		if (!IsSameConfigurationExactlyExists(path, datasourceName, databaseHost, databasePort, databaseServiceName))
		{
			DisableConfigurations(path, datasourceName);
			AppendConfiguration(path, datasourceName, databaseHost, databasePort, databaseServiceName);
		}
	}

	public static void CopyConfigurations(TnsNamesOraFile sourceFile, TnsNamesOraFile targetFile)
	{
		IEnumerable<TnsNamesConfiguration> enumerable = sourceFile.Configurations.Where((TnsNamesConfiguration configuration) => configuration.IsActive);
		foreach (TnsNamesConfiguration item in enumerable)
		{
			CopyConfiguration(item, targetFile);
		}
	}
