	public static bool CheckFileExistence(string targetFile)
	{
		if (!File.Exists(targetFile))
		{
			string directoryName = Path.GetDirectoryName(targetFile);
			if (!Directory.Exists(directoryName))
			{
				UtilsLoggerWrapper.Info($"Directory \"{directoryName}\" doesn't exists. It will be created.");
				try
				{
					Directory.CreateDirectory(directoryName);
				}
				catch (Exception arg)
				{
					UtilsLoggerWrapper.Error($"ERROR! Can't create directory \"{directoryName}\"! Exception: \"{arg}\"");
					throw;
				}
				UtilsLoggerWrapper.Info($"Directory \"{directoryName}\" was successfully created.");
			}
			return false;
		}
		return true;
	}

	public static bool IsSameConfigurationExactlyExists(string path, string datasource, string host, string port, string service)
	{
		if (!File.Exists(path))
		{
			return false;
		}
		string[] array = File.ReadAllLines(path);
		Regex regex = new Regex("\\s*(\\S+)\\s*=.*?\\(\\s*description\\s*=.*?\\(\\s*address\\s*=\\s*\\(\\s*protocol\\s*=.*?\\)\\s*\\(\\s*host\\s*=\\s*([^\\s\\)]+)\\s*\\)\\s*\\(\\s*port\\s*=\\s*([^\\s\\)]+)\\s*\\).*?\\(\\s*connect_data\\s*=.*?\\(\\s*service_name\\s*=\\s*([^\\s\\)]+)\\s*\\).*?\\)\\s*\\)", RegexOptions.IgnoreCase | RegexOptions.Singleline);
		string text = null;
		for (int i = 0; i < array.Length; i++)
		{
			if (string.IsNullOrEmpty(array[i].Trim()) || array[i].TrimStart(new char[0]).StartsWith('#'.ToString()))
			{
				text = null;
				continue;
			}
			text += array[i];
			if (!string.IsNullOrEmpty(text) && regex.IsMatch(text))
			{
				Match match = regex.Match(text);
				string value = match.Groups[1].Value;
				string value2 = match.Groups[2].Value;
				string value3 = match.Groups[3].Value;
				string value4 = match.Groups[4].Value;
				if (value.ToUpper() == datasource.ToUpper() && value2.ToUpper() == host.ToUpper() && value3.ToUpper() == port.ToUpper() && value4.ToUpper() == service.ToUpper())
				{
					return true;
				}
				text = null;
			}
		}
		return false;
	}

	public static void AppendConfiguration(string path, string datasource, string host, string port, string service)
	{
		UtilsLoggerWrapper.Info($"Appending configuration {datasource} to file {path}");
		UtilsLoggerWrapper.Info($"Building text for configuration {datasource}");
		bool flag = File.Exists(path);
		StringBuilder stringBuilder = new StringBuilder();
		if (!flag)
		{
			stringBuilder.AppendLine($"{'#'} TNSNAMES.ORA Network Configuration File: {path}");
			stringBuilder.AppendLine($"{'#'} Generated by SAUMI installer");
		}
		stringBuilder.AppendLine();
		stringBuilder.AppendLine($"{datasource} =");
		stringBuilder.AppendLine("  (DESCRIPTION =");
		stringBuilder.AppendLine("    (ADDRESS_LIST =");
		stringBuilder.AppendLine($"      (ADDRESS = (PROTOCOL = TCP)(HOST = {host})(PORT = {port}))");
		stringBuilder.AppendLine("    )");
		stringBuilder.AppendLine("    (CONNECT_DATA =");
		stringBuilder.AppendLine($"     (SERVICE_NAME = {service})");
		stringBuilder.AppendLine("    )");
		stringBuilder.AppendLine("  )");
		UtilsLoggerWrapper.Info($"Writing builded configuration text to end of file \"{path}\"");
		FileStream fileStream = File.Open(path, (!flag) ? FileMode.CreateNew : FileMode.Append);
		StreamWriter streamWriter = new StreamWriter(fileStream, Encoding.Default);
		streamWriter.Write(stringBuilder.ToString());
		streamWriter.Close();
		streamWriter.Dispose();
		fileStream.Close();
		fileStream.Dispose();
	}

