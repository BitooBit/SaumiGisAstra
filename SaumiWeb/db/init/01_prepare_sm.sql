-- Prepare SM / smpwd and stub roles used by schema dump
ALTER SESSION SET CONTAINER = FREEPDB1;

BEGIN
  EXECUTE IMMEDIATE 'CREATE USER SM IDENTIFIED BY smpwd DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -1920 THEN
      EXECUTE IMMEDIATE 'ALTER USER SM IDENTIFIED BY smpwd';
    ELSE
      RAISE;
    END IF;
END;
/

GRANT CONNECT, RESOURCE, CREATE VIEW, CREATE SYNONYM, CREATE SEQUENCE,
      CREATE PROCEDURE, CREATE TRIGGER, CREATE TYPE, CREATE JOB TO SM;
ALTER USER SM QUOTA UNLIMITED ON USERS;

-- Roles referenced by schema grants (stubs — enough for import / login)
BEGIN
  FOR r IN (
    SELECT column_value AS role_name FROM TABLE(sys.odcivarchar2list(
      'SM_ALLUSERS','SM_ALL_SELECT',
      'SM_CANCHARGE','SM_CANCREATE_PRIVATES','SM_CANDICTS','SM_CANFINANALIZE',
      'SM_CANGIS','SM_CANGIS_WRITE','SM_CANMOVE','SM_CANMOVESHARE','SM_CANPAY',
      'SM_CAN_CREATE_ATO','SM_CHANGE_BUILDINGS','SM_CHANGE_STATES',
      'SM_CREATE_BUILDINGS','SM_CREATE_COMPLEX_PROPERTY','SM_CREATE_DOC',
      'SM_CREATE_ENGINF','SM_CREATE_GROUNDS','SM_CREATE_ORGANISATIONS',
      'SM_CREATE_PROPERTY','SM_CREATE_TRANSPORT','SM_CREATE_UNCONSTR',
      'SM_GMP_COMMUNICATION','SM_UPDATE_OBJECTS',
      'VBYKAREVA','VPANOV'
    ))
  ) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'CREATE ROLE ' || r.role_name;
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -1921 THEN RAISE; END IF;
    END;
    BEGIN
      EXECUTE IMMEDIATE 'GRANT ' || r.role_name || ' TO SM';
    EXCEPTION
      WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
/
